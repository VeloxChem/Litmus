#ifndef provenance_hpp
#define provenance_hpp

#include <fstream>
#include <string>

namespace ost {  // ost namespace

/// Records the configuration file text of the current run, so that every
/// generated file can state how to regenerate it.
/// @param config_text The verbatim contents of the configuration file.
void set_generation_config(const std::string& config_text);

/// Returns the Litmus source revision this executable was built from.
/// @return The `git describe --always --dirty` revision, or "unknown".
std::string litmus_revision();

/// Builds the comment banner placed at the top of every generated file. It
/// opens with the VeloxChem BSD-3-Clause license header, then marks the file as generated by Litmus, names the Litmus revision, and,
/// when a configuration has been recorded, gives the command and the
/// configuration needed to regenerate the file.
/// @return The banner, as `//` comment blocks each followed by a blank line.
std::string generated_file_banner();

/// Opens (truncating) a generated output file and writes the banner to it.
/// @param fstream The file stream to open.
/// @param fname The output file name.
void open_generated_file(std::ofstream& fstream, const std::string& fname);

}  // namespace ost

#endif /* provenance_hpp */
